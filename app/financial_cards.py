def get_relevant_cards(context: dict, max_cards: int = 3) -> list[dict]:
    matched = []
    for card in CARDS:
        try:
            if card["condition"](context):
                matched.append({"id": card["id"], "title": card["title"], "body": card["body"]})
        except (KeyError, ZeroDivisionError, TypeError):
            continue  # пропускаем карточку, если в контексте не хватает нужных данных
        if len(matched) >= max_cards:
            break
    return matched